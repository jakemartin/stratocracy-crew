// Test Engineer's gate for §4.11 row 10, PART (b) — headless replayer + §4.10's
// canonical state hash.
//
// WHAT THIS SUITE CLOSES, and why that is four IDs and not five. Part (b) runs
// T-SAVE-01/02/03/05/06. `T-SAVE-06` asserts the hash is identical across the
// HEADLESS and IN-ENGINE builds; it is marked † in §4.11 and asserted jointly with
// T-INT-02, which replays IN-ENGINE -- so it cannot close in a headless build, and
// it is printed by name at the end rather than folded into the tally. The reason
// this comment used to give -- that T-INT-02 needed a vendored replayer a ruling
// deferred -- is spent, Save and Replay having been vendored at f5fdb69. The four
// this suite closes are T-SAVE-01, 02, 03 and 05.
//
// THE LOG CARRIES THE COMPLETE §4.9 COMMAND SET. Q29's conservative reading closes
// an acceptance ID only when its whole written fixture set ran, and §4.11 puts
// closure on rows 4-5 completing the command set and row 6 completing T-SAVE-02's
// determinism composition. All three have landed, so the canonical log below
// exercises `Move`, `Attack`, `Build`, `Capture` and `EndTurn`, and a segment of it
// is generated by row 6's AI rather than hand-written -- which is what puts T-AI-06
// inside T-SAVE-02's composition instead of beside it.
//
// THE CHECK RECOMPUTES; IT DOES NOT DELEGATE. The serialisation check below builds
// §4.10's byte stream independently, field by field, from the fixture's own values
// -- it never asks `canonicalStateBytes` what it thinks the order is. A check that
// compared two calls to the implementation would agree with any field order,
// correct or not, and the field order IS the invariant here.
//
// THE HAND-BUILT FIXTURE TABLES ARE BUILT HERE, not loaded from data/. Loading the
// shipped CSVs would make every check that turns on a stat depend on row 2's files,
// and every number those checks turn on would then be a value nobody in this file
// chose. Every check from GATE-REPLAY-SETUP through T-SAVE-05 runs on those tables.
//
// GATE-REPLAY-FIXTURE IS THE ONE EXCEPTION, and it is an exception on purpose. It
// asserts over `data/parity_fixture.save`, the committed §4.10 file T-INT-02 replays
// IN-ENGINE, and the UE side reads `data/units.csv`, `data/terrain.csv` and
// `data/ferrum_crossing.json` -- the bytes `sync_stratdata.py` vendors. A parity
// fixture seeded from tables nobody ships would compare two different games, so this
// one check loads the real files and turns on no number of its own: it asserts a
// replay succeeds, that a carried digest equals a recomputed one, and that re-emitting
// reproduces the committed bytes. Both worlds seed through `seedFromScenario`, the
// only Scenario -> GameState mapping in the project.
