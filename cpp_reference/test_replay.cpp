static int g_total = 0;
static int g_fail  = 0;

static void check(const char* name, bool cond) {
    ++g_total;
    if (cond) { std::printf("PASS  %s\n", name); }
    else      { std::printf("FAIL  %s\n", name); ++g_fail; }
}

// ---------------------------------------------------------------------------
// Fixture. A 5x3 board: plains, with a factory per SIDE -- (0,2) side 0's, (4,2)
// side 1's -- and one neutral town at (2,1) to capture.
//
// THE FACTORY COUNT IS LOAD-BEARING, not scenery. §2.8's domination backstop
// (T-TURN-03) ends a match the moment one side holds EVERY factory, and row 5 checks
// it at `beginTurn`. A fixture with a single factory is therefore over before its
// first command: the match ends inside `openTurn` and every later command is refused
// "no match is running". Two factories, one per side, is the smallest board on which
// a turn can actually be played.
// ---------------------------------------------------------------------------
static std::vector<TerrainDef> fixtureTerrain() {
    std::vector<TerrainDef> t(3);
    t[0].id = "Plains";  t[0].moveCost = 1; t[0].defensePct = 0; t[0].passLand = true;
    t[1].id = "Factory"; t[1].moveCost = 1; t[1].defensePct = 0; t[1].passLand = true;
    t[1].capturable = true; t[1].incomeFame = 100; t[1].isSpawnPoint = true;
    t[2].id = "Town";    t[2].moveCost = 1; t[2].defensePct = 10; t[2].passLand = true;
    t[2].capturable = true; t[2].incomeFame = 25;
    return t;
}

