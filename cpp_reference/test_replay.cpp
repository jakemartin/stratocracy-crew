static GameUnit mkUnit(int id, int side, int defIndex, int col, int row, int hp) {
    GameUnit u;
    u.id = id; u.side = side; u.defIndex = defIndex;
    u.hex = offsetToAxial(col, row);
    u.placement = u.hex;
    u.hp = hp;
    return u;
}

static GameState fixtureState(const std::vector<UnitDef>& ud,
                              const std::vector<TerrainDef>& td) {
    GameState g;
    g.bounds.cols = 5; g.bounds.rows = 3;
    g.terrain.assign(15, 0);
    g.terrain[2 * 5 + 0] = 1;                 // Factory at (0,2), side 0's
    g.terrain[2 * 5 + 4] = 1;                 // Factory at (4,2), side 1's
    g.terrain[1 * 5 + 2] = 2;                 // Town    at (2,1), neutral

    g.units.push_back(mkUnit(1, 0, 0, 1, 1, 10));   // side 0 Infantry
    g.units.push_back(mkUnit(2, 0, 1, 0, 0, 20));   // side 0 Tank  (the flag)
    g.units.push_back(mkUnit(3, 1, 0, 4, 1, 10));   // side 1 Infantry
    g.nextUnitId = 4;
    g.flagUnit[0] = 2;
    g.flagUnit[1] = -1;                             // side 1 designates none

    initSide(g.economy, 0, 400);
    initSide(g.economy, 1, 400);
    Objective f0; f0.hex = offsetToAxial(0, 2); f0.owner = 0; f0.terrainIndex = 1;
    Objective f1; f1.hex = offsetToAxial(4, 2); f1.owner = 1; f1.terrainIndex = 1;
    Objective tn; tn.hex = offsetToAxial(2, 1); tn.owner = OWNER_NEUTRAL;
    tn.terrainIndex = 2;
    g.economy.objectives.push_back(f0);
    g.economy.objectives.push_back(f1);
    g.economy.objectives.push_back(tn);
    g.economy.captureTurns = 1;

    std::string err;
    initMatch(g.turn, 0, 20, err);
    // initMatch leaves the phase TurnPending; the first turn is opened the same way
    // every later one is, so the initial state here is a state a real match reaches.
    RulesTables t;
    t.units = &ud;
    t.terrain = &td;
    openTurn(g, t);
    return g;
}

static SaveCommand cmd(SaveCommandKind k, int turn, int side, int unitId,
                       int col, int row, bool hasHex, bool hasUnit) {
    SaveCommand c;
    c.turn = turn; c.side = side; c.kind = k;
    c.unitId = unitId;
    if (hasHex) c.hex = offsetToAxial(col, row);
    c.hasHex = hasHex; c.hasUnit = hasUnit;
    return c;
}

// The canonical log: all five §4.9 commands, side 0's turn.
//   Move    #1 (1,1) -> (2,1)   Infantry onto the neutral town
//   Move    #2 (0,0) -> (1,0)   the Tank, BEFORE the build -- a unit the build
//                               spawns can box a route in, and Q3's conservative
//                               reading makes any occupied hex block pathing
//   Capture side 0              the tick that takes the town (captureTurns == 1)
//   Build   Infantry at (0,2)   side 0's own factory, unoccupied
//   EndTurn
static std::vector<SaveCommand> canonicalLog() {
    std::vector<SaveCommand> log;
    log.push_back(cmd(SaveCommandKind::Move,    1, 0, 1, 2, 1, true,  true));
    log.push_back(cmd(SaveCommandKind::Move,    1, 0, 2, 1, 0, true,  true));
    log.push_back(cmd(SaveCommandKind::Capture, 1, 0, 0, 0, 0, false, false));
    log.push_back(cmd(SaveCommandKind::Build,   1, 0, 0, 0, 2, true,  true));
    log.push_back(cmd(SaveCommandKind::EndTurn, 1, 0, 0, 0, 0, false, false));
    return log;
}

// ---------------------------------------------------------------------------
// Row 6's AI, driven against the replayer's own state. Its commands enter the log
// exactly as a player's would -- which is the property row 6's stub claims and the
// reason T-AI-06's determinism composes into T-SAVE-02 rather than sitting beside it.
// ---------------------------------------------------------------------------
static AiState aiViewOf(const GameState& g, const std::vector<UnitDef>& ud,
                        const std::vector<TerrainDef>& td) {
    AiState s;
    s.bounds = g.bounds;
    s.terrain = g.terrain;
    s.unitDefs = ud;
    s.terrainDefs = td;
    s.economy = g.economy;
    s.turn = g.turn;
    s.builtThisTurn = g.turn.builtThisTurn;
    for (const GameUnit& u : g.units) {
        AiUnit a;
        a.id = u.id; a.side = u.side; a.defIndex = u.defIndex; a.hex = u.hex;
        a.hp = u.hp; a.isFlag = isFlagUnit(g, u);
        s.units.push_back(a);
    }
    return s;
}

// Converts one AiCommand into the §4.9 vocabulary the log records. Attack is tagged
// by TARGET HEX (§4.10's `{turn, side}` plus §4.9's `Attack{unit, targetHex}`), so
// the target's id is resolved to its hex here and never stored as an id.
static bool aiCommandToSave(const GameState& g, const AiCommand& a, int turn, int side,
                            SaveCommand& out) {
    out = SaveCommand();
    out.turn = turn; out.side = side;
    switch (a.kind) {
    case AiCommandKind::Move:
        out.kind = SaveCommandKind::Move; out.unitId = a.unitId; out.hex = a.hex;
        out.hasUnit = true; out.hasHex = true; return true;
    case AiCommandKind::Attack: {
        const GameUnit* target = findGameUnit(g, a.targetId);
        if (target == nullptr) return false;
        out.kind = SaveCommandKind::Attack; out.unitId = a.unitId; out.hex = target->hex;
        out.hasUnit = true; out.hasHex = true; return true;
    }
    case AiCommandKind::Build:
        out.kind = SaveCommandKind::Build; out.unitId = a.defIndex; out.hex = a.hex;
        out.hasUnit = true; out.hasHex = true; return true;
    case AiCommandKind::EndTurn:
        out.kind = SaveCommandKind::EndTurn; return true;
    }
    return false;
}

// Plays side 1's turn with row 6's AI, appending every command it emits to `log` and
// applying each to `g`. Bounded, so a misbehaving AI cannot hang the gate.
static void appendAiTurn(GameState& g, std::vector<SaveCommand>& log,
                         const RulesTables& t, const std::vector<UnitDef>& ud,
                         const std::vector<TerrainDef>& td, int side) {
    for (int guard = 0; guard < 32; ++guard) {
        const AiState view = aiViewOf(g, ud, td);
        const AiCommand a = nextCommand(view, side);
        SaveCommand sc;
        if (!aiCommandToSave(g, a, g.turn.turnNumber, side, sc)) break;
        const ReplayResult r = applyCommand(g, sc, t);
        if (!r.ok) break;                 // the AI proposed something the rules refuse
        log.push_back(sc);
        if (a.kind == AiCommandKind::EndTurn) break;
    }
}

